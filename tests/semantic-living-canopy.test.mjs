import assert from 'node:assert/strict';import {readFileSync} from 'node:fs';import {canopyModel} from '../semantic-living-canopy.mjs';
const manifest=JSON.parse(readFileSync(new URL('../data/living-universe.json',import.meta.url),'utf8'));
const stages=canopyModel(manifest);
assert.deepEqual(stages.map(s=>s.kind),['root','trunk','branch','leaf','flower','fruit']);
assert(stages.every(s=>s.entries.every(e=>e.kind===s.kind)));
assert(stages.find(s=>s.kind==='root').entries.every(e=>e.url.startsWith('https://github.com/')));
assert(stages.find(s=>s.kind==='fruit').entries.every(e=>!e.url.startsWith('https://github.com/')));
assert(stages.flatMap(s=>s.entries).every(e=>!e.attested||e.roots.length>0));
const html=readFileSync(new URL('../semantic-scene.html',import.meta.url),'utf8');
assert(html.includes('id="living-canopy"'));assert(html.includes('semantic-living-canopy.mjs'));
const canopySource=readFileSync(new URL('../semantic-living-canopy.mjs',import.meta.url),'utf8');
const canopyCss=readFileSync(new URL('../semantic-living-canopy.css',import.meta.url),'utf8');
assert(canopySource.includes("entry.kind==='root'?[entry]:entry.roots"),'root journeys must originate from repository roots');
assert(canopySource.includes('Intermediate connections are contextual'),'contextual edges must not be presented as attested');
assert(canopySource.includes('Outcome verification is incomplete'),'unverified fruit must expose evidence gap');
assert(canopySource.includes("routeBody.replaceChildren()"),'route must clear stale selected lineage');
assert(canopyCss.includes('canopy-route-step'),'visual journey styling must be present');
assert(canopyCss.includes('@media(max-width:650px)'),'journey must support narrow mobile screens');
console.log('Living canopy biological, evidence and integration contracts passed');
assert(canopySource.includes("function navigateStage(direction)"),'stage navigation must be reversible');
assert(canopySource.includes("Only documented entities are selectable"),'stage navigation must distinguish discovery from lineage');
assert(canopySource.includes("No lineage inferred"),'empty stages must not fabricate outcomes');
assert(canopySource.includes("previous.disabled=index<=0"),'root boundary must disable backward navigation');
assert(canopySource.includes("next.disabled=index>=LAYERS.length-1"),'fruit boundary must disable forward navigation');

assert(canopySource.includes('function renderOverview()'),'curated stage atlas must be rendered');
assert(canopySource.includes('stage.entries.filter(e=>e.verifiedOutcome)'),'fruit counts must use verified outcomes only');
assert(canopySource.includes("select.value=stage.kind;search.value='';render()"),'stage overview must navigate to the existing canopy');
assert(canopySource.includes('Counts describe the curated manifest, not live health'),'overview must disclaim live status');
assert(canopyCss.includes('.canopy-evidence-track'),'spectral atlas must be styled');
assert(canopyCss.includes('@media(max-width:480px)'),'atlas must adapt to narrow mobile');

const sceneSource=readFileSync(new URL('../semantic-scene-ui.mjs',import.meta.url),'utf8');
assert(canopySource.includes("new Map(stages.flatMap"),'selection must resolve only manifest-backed entities');
assert(canopySource.includes("aift:lineage-selected"),'canopy must consume spatial selection events');
assert(canopySource.includes("aift:lineage-select"),'canopy must publish a selection for the spatial scene');
assert(sceneSource.includes("aift:lineage-selected"),'spatial scene must publish selected entities');
assert(sceneSource.includes("aift:lineage-select"),'spatial scene must consume canopy selection');
assert(canopySource.includes("if(typeof id!=='string'||!byId.has(id))return"),'unrecognized entity IDs must be ignored');
assert(canopySource.includes("button.dataset.entityId=entry.id"),'rendered entity controls must retain stable identity');
assert(canopySource.includes("aria-pressed"),'selected entity must have accessible state');
assert(canopySource.includes("if(id===null)"),'spatial reset must clear stale canopy selection');
console.log('Cross-surface canopy and constellation selection contracts passed');
