import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {buildExplorationIndex} from '../semantic-federation-exploration-contract.mjs';
const html=readFileSync(new URL('../semantic-scene.html',import.meta.url),'utf8');
const js=readFileSync(new URL('../semantic-spectral-journey.mjs',import.meta.url),'utf8');
const css=readFileSync(new URL('../semantic-spectral-journey.css',import.meta.url),'utf8');
assert.match(html,/id="spectral-journey"/);
assert.match(html,/semantic-spectral-journey\.mjs/);
assert.match(html,/semantic-spectral-journey\.css/);
assert.match(js,/buildExplorationIndex\(manifest\)/);
assert.match(js,/aift:lineage-selected/);
assert.match(js,/aift:lineage-select/);
assert.match(js,/index\.journey\(selected\.entity\.id\)/);
assert.match(js,/outcome\?\.verified/);
assert.match(css,/prefers-reduced-motion:reduce/);
assert.match(css,/:focus-visible/);
const manifest={nodes:[{id:'repo',kind:'root',label:'Source',url:'https://github.com/example/source'},{id:'product',kind:'fruit',label:'Product',url:'https://example.org/product'}],edges:[{from:'repo',to:'product',relation:'contributes-to',status:'source-backed',evidenceUrl:'https://example.org/evidence'}]};
const model=buildExplorationIndex(manifest);
assert.equal(model.outcomes[0].verified,true);
assert.equal(model.journey('product').length,1);
assert.equal(model.journey('product')[0].evidence.length,1);
assert.equal(buildExplorationIndex({...manifest,edges:[]}).outcomes[0].verified,false);
assert.equal(buildExplorationIndex({...manifest,nodes:[manifest.nodes[0],{...manifest.nodes[1],url:'https://github.com/example/source'}]}).outcomes[0].verified,false);
console.log('Spectral journey integration and evidence contracts passed');
